number = float(input("Digite o número 1 "))
number2 = float(input("Digite o número 2 "))

operator = input("O que você quer fazer ? /, *, +, -")

if (operator == "/"):
     
     print (number/number2, "Essa é a dvisão dos numeros")

if operator == "*":
      print (number*number2, "Essa é a multiplicação dos numeros")

if operator == "+":
       print (number+number2, "Essa é a soma dos numeros")

if operator == "-":
       print (number-number2, "Essa é a subtração dos numeros")